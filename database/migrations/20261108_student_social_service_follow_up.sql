BEGIN;
ALTER TABLE students ADD COLUMN social_service_eligible_period_id bigint NULL,
 ADD COLUMN social_service_eligible_period_updated_at timestamptz NULL,
 ADD COLUMN social_service_eligible_period_updated_by bigint NULL REFERENCES users(id) ON DELETE RESTRICT,
 ADD CONSTRAINT fk_students__ss_eligible_period FOREIGN KEY (social_service_eligible_period_id) REFERENCES academic_periods(id) ON DELETE RESTRICT;
CREATE INDEX idx_students__ss_eligible_period_updated_by ON students(social_service_eligible_period_updated_by);
CREATE INDEX idx_students__ss_eligible_period_id ON students(social_service_eligible_period_id);
CREATE TABLE social_service_follow_up_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_social_service_follow_up_reviews PRIMARY KEY,
 social_service_id bigint NOT NULL REFERENCES social_services(id) ON DELETE RESTRICT,
 period_id bigint NOT NULL REFERENCES academic_periods(id) ON DELETE RESTRICT,
 assessment varchar(20) NOT NULL CHECK (assessment IN ('consistent','low_progress')),
 notes varchar(1000) NULL,
 created_by bigint NULL REFERENCES users(id), updated_by bigint NULL REFERENCES users(id), deleted_by bigint NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at timestamptz NULL,
 CONSTRAINT uq_social_service_follow_up_reviews__service_period UNIQUE(social_service_id,period_id)
);
CREATE INDEX idx_social_service_follow_up_reviews__period_id ON social_service_follow_up_reviews(period_id);
CREATE INDEX idx_social_service_follow_up_reviews__deleted_at ON social_service_follow_up_reviews(deleted_at);
CREATE VIEW vw_student_social_service_follow_up AS
SELECT s.id AS student_id, t.id AS social_service_id, e.id AS eligible_period_id, e.code AS eligible_period_code,
 p.id AS tracking_period_id, p.code AS tracking_period_code,
 CASE WHEN e.id IS NOT NULL AND p.id IS NOT NULL AND e.start_date <= p.start_date THEN
 (SELECT count(*)::int FROM academic_periods a WHERE a.deleted_at IS NULL AND a.start_date > e.start_date AND a.start_date <= p.start_date) END AS elapsed_semesters,
 d.approved_documents_count, d.last_approved_at,
 CASE WHEN t.status='released' THEN 'released' WHEN t.status='non_compliant' THEN 'non_compliant'
 WHEN d.approved_documents_count > 0 THEN 'in_progress'
 WHEN e.id IS NULL OR p.id IS NULL OR e.start_date > p.start_date THEN 'pending_setup'
 WHEN (SELECT count(*) FROM academic_periods a WHERE a.deleted_at IS NULL AND a.start_date > e.start_date AND a.start_date <= p.start_date) >= 3 THEN 'non_compliant'
 WHEN (SELECT count(*) FROM academic_periods a WHERE a.deleted_at IS NULL AND a.start_date > e.start_date AND a.start_date <= p.start_date) = 2 THEN 'third_notice'
 WHEN (SELECT count(*) FROM academic_periods a WHERE a.deleted_at IS NULL AND a.start_date > e.start_date AND a.start_date <= p.start_date) = 1 THEN 'second_notice'
 ELSE 'first_notice' END::text AS status,
 r.assessment AS progress_assessment, r.notes, r.updated_at AS reviewed_at
FROM students s
LEFT JOIN academic_periods e ON e.id=s.social_service_eligible_period_id AND e.deleted_at IS NULL
LEFT JOIN LATERAL (SELECT * FROM academic_periods WHERE is_active AND deleted_at IS NULL ORDER BY start_date DESC,id DESC LIMIT 1) p ON true
LEFT JOIN LATERAL (SELECT * FROM social_services WHERE student_id=s.id AND deleted_at IS NULL AND status<>'cancelled'
 ORDER BY (status='released') DESC,(status<>'non_compliant') DESC,created_at DESC,id DESC LIMIT 1) t ON true
LEFT JOIN LATERAL (SELECT count(*)::int AS approved_documents_count,max(reviewed_at) AS last_approved_at FROM expedient_documents
 WHERE student_id=s.id AND tramite_type='social_service' AND tramite_id=t.id AND origin='uploaded' AND status='approved' AND deleted_at IS NULL) d ON true
LEFT JOIN social_service_follow_up_reviews r ON r.social_service_id=t.id AND r.period_id=p.id AND r.deleted_at IS NULL
WHERE s.deleted_at IS NULL;
COMMIT;
